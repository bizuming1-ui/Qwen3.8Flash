#!/usr/bin/env node
/**
 * Copy the few CodeMirror 5 files we need out of node_modules into
 * server/public/vendor/ so the app runs with ZERO runtime npm dependencies
 * and works fully offline (no CDN). Run automatically by `npm install`.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'node_modules', 'codemirror');
const DEST = path.join(ROOT, 'server', 'public', 'vendor');

const FILES = [
  ['lib/codemirror.js', 'codemirror.js'],
  ['lib/codemirror.css', 'codemirror.css'],
  ['theme/material-darker.css', 'theme-material-darker.css'],
  ['mode/python/python.js', 'mode-python.js'],
  ['mode/markdown/markdown.js', 'mode-markdown.js'],
  ['mode/javascript/javascript.js', 'mode-javascript.js'],
  ['mode/shell/shell.js', 'mode-shell.js'],
  ['mode/yaml/yaml.js', 'mode-yaml.js'],
  ['addon/edit/closebrackets.js', 'addon-closebrackets.js'],
  ['addon/comment/comment.js', 'addon-comment.js'],
  ['addon/display/autorefresh.js', 'addon-autorefresh.js'],
  ['addon/selection/active-line.js', 'addon-active-line.js'],
  ['addon/fold/foldcode.js', 'addon-foldcode.js'],
  ['addon/fold/foldgutter.js', 'addon-foldgutter.js'],
  ['addon/fold/foldgutter.css', 'addon-foldgutter.css'],
  ['addon/fold/brace-fold.js', 'addon-brace-fold.js'],
  ['addon/fold/comment-fold.js', 'addon-comment-fold.js'],
  ['addon/fold/indent-fold.js', 'addon-indent-fold.js'],
];

function main() {
  if (!fs.existsSync(SRC)) {
    console.error('[vendor] codemirror not installed. Run `npm install` first.');
    process.exitCode = 1;
    return;
  }
  fs.mkdirSync(DEST, { recursive: true });
  let ok = 0;
  for (const [from, to] of FILES) {
    const src = path.join(SRC, ...from.split('/'));
    if (!fs.existsSync(src)) {
      console.warn(`[vendor] missing (skipped): ${from}`);
      continue;
    }
    fs.copyFileSync(src, path.join(DEST, to));
    ok += 1;
  }
  fs.writeFileSync(
    path.join(DEST, 'SOURCE.txt'),
    `Vendored from npm package codemirror@5.65.16 (MIT license).\n` +
      `Generated by scripts/vendor-assets.js — do not edit by hand.\n` +
      `${ok} files copied.\n`
  );
  console.log(`[vendor] copied ${ok} CodeMirror files -> server/public/vendor/`);
}

main();
